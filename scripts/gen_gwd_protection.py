#!/usr/bin/env python3
"""Regenerate src/main/resources/com/loadoutlab/data/gwd_protection.json.

Source: the OSRS Wiki "God Wars Dungeon" page, section "God equipment"
(the area table + the slot-by-god item table). Item names are the wiki
page names (lower-cased) - the gear corpus matches them by name, so any
version of the item counts (charged/uncharged, (or) ornament kits...).

The ROUTE per general follows the owner's decision (2026-10-21, "Follow
the wiki's route table"): each encampment's own corner of the main
chamber + the encampment row, unioned (Mural F-01M5G95132EW0Z6G11S39XSXG4).

Usage: python3 scripts/gen_gwd_protection.py [--wikitext FILE]
"""
import json
import pathlib
import re
import sys
import urllib.request

API = ("https://oldschool.runescape.wiki/api.php?action=parse&page=God_Wars_Dungeon"
       "&prop=wikitext&section={}&format=json")
UA = "LoadoutLab-data/1.0 (github ajkatz)"
OUT = pathlib.Path(__file__).resolve().parent.parent / "src/main/resources/com/loadoutlab/data/gwd_protection.json"
GODS = ["saradomin", "zamorak", "bandos", "armadyl", "zaros"]  # the item table's column order

# The general's room and its bodyguards, per god, with the route's gods.
ROUTES = {
    "bandos": {"gods": ["armadyl", "bandos", "zamorak"],
               "monsters": ["general graardor", "sergeant strongstack", "sergeant steelwill", "sergeant grimspike"]},
    "armadyl": {"gods": ["armadyl", "bandos", "saradomin", "zamorak"],
                "monsters": ["kree'arra", "wingman skree", "flockleader geerin", "flight kilisa"]},
    "saradomin": {"gods": ["armadyl", "saradomin", "zamorak"],
                  "monsters": ["commander zilyana", "starlight", "growler", "bree"]},
    "zamorak": {"gods": ["bandos", "saradomin", "zamorak"],
                "monsters": ["k'ril tsutsaroth", "tstanon karlak", "zakl'n gritch", "balfrug kreeyath"]},
}


def section_text(index):
    req = urllib.request.Request(API.format(index), headers={"User-Agent": UA})
    with urllib.request.urlopen(req) as resp:
        return json.load(resp)["parse"]["wikitext"]["*"]


def item_table(wikitext):
    """{god: [names]} from the slot-by-god table (the one whose header has 'Slot')."""
    start = wikitext.index("! Slot")
    table = wikitext[start:wikitext.index("|}", start)]
    items = {god: [] for god in GODS}
    for row in table.split("|-")[1:]:
        cells = re.split(r"\n\|", "\n" + row.split("\n", 2)[-1] if row.startswith("\n!") else row)
        cells = [c for c in re.split(r"\n\|(?!\})", row) if c.strip()]
        # cells[0] holds "! Slot" header line plus the first god cell
        god_cells = cells[-len(GODS):]
        for god, cell in zip(GODS, god_cells):
            for name in re.findall(r"\{\{plink\|([^|}]+)", cell):
                name = name.strip().lower()
                if name not in items[god]:
                    items[god].append(name)
    return items


def main():
    if "--wikitext" in sys.argv:
        wikitext = pathlib.Path(sys.argv[sys.argv.index("--wikitext") + 1]).read_text(encoding="utf-8")
    else:
        wikitext = section_text(9)
    items = item_table(wikitext)
    out = {
        "_comment": ("God Wars Dungeon protection (generated by scripts/gen_gwd_protection.py from the OSRS Wiki "
                     "'God Wars Dungeon' God equipment section). Followers ignore you while you WEAR an item of "
                     "their god; routes = the encampment's corner + encampment rows, unioned (Andrew 2026-10-21). "
                     "zaros = the Ancient Prison (Nex's bank via Ashuelot Reis), an optional chip."),
        "routes": ROUTES,
        "items": items,
    }
    OUT.write_text(json.dumps(out, indent=1, ensure_ascii=True) + "\n", encoding="utf-8")
    print({god: len(names) for god, names in items.items()})


if __name__ == "__main__":
    main()
