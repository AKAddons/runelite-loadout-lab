package com.loadoutlab.data;

import com.google.gson.reflect.TypeToken;
import java.util.*;

import static com.loadoutlab.data.JsonResources.*;

public class DataService {
    static final String GEAR_RESOURCE = "gear_prices.json.gz";
    static final String REQUIREMENTS_RESOURCE = "equipment_requirements.json.gz";
    static final String MONSTER_RESOURCE = "monsters.json.gz";
    static final String SPELL_RESOURCE = "spells.json.gz";
    static final String ALIAS_RESOURCE = "equipment_aliases.json.gz";
    static final String NAME_RULES_RESOURCE = "name_rules.json";

    // Name-matching tables, generated by scripts/gen_name_rules.py. Quest
    // rules stay in resource order: a quest named by two rules must still
    // dedup at its FIRST position in the LinkedHashSet that questsFor builds.
    static class NameRules {
        Map<String, Integer> spellLevels = Map.of();
        List<String> slayerContains = List.of(), slayerStartsWith = List.of();
        List<QuestRule> questRules = List.of();
    }

    static class QuestRule {
        List<String> terms = List.of();
        String quest;
    }

    static final NameRules RULES = read(NAME_RULES_RESOURCE, NameRules.class);

    static {
        // Fail LOUD, unlike the fail-soft tables elsewhere. An empty table here
        // would silently pin every spell to level 1 and drop every quest
        // requirement - that changes DPS and gear recommendations with no
        // visible error.
        if (RULES.spellLevels.isEmpty() || RULES.slayerContains.isEmpty() || RULES.slayerStartsWith.isEmpty() || RULES.questRules.isEmpty()) throw new IllegalStateException("Empty table in " + NAME_RULES_RESOURCE);
    }

    public LoadoutData load() {
        List<GearItem> gear = priceChargedTwins(loadGear());
        List<MonsterStats> monsters = normalizeQuestVersions(loadMonsters());
        List<SpellStats> spells = loadSpells();
        Map<Integer, GearItem> gbi = new HashMap<>();
        gear.forEach(item -> gbi.put(item.id, item));
        return new LoadoutData(gear, monsters, spells, gbi, loadAliases(gear));
    }

    // Variant id -> base id (ornament/locked/degraded, identical stats),
    // plus every uncharged, inactive, broken or locked WEAPON version behind
    // its charged twin (ISS-01M5QQV2TGQ5X730T0JJ75S1RD, Andrew 2026-10-24:
    // "let's only consider charged versions of weapons, don't think about eye
    // of ayak uncharged or obligator uncharged"): never suggested, and owning
    // one is owning the twin you charge before the trip.
    Map<Integer, Integer> loadAliases(List<GearItem> gear) {
        Map<Integer, Integer> aliases = read(ALIAS_RESOURCE, new TypeToken<Map<Integer, Integer>>() { }.getType());
        aliases.entrySet().removeIf(e -> e.getKey().intValue() == e.getValue());
        for (var twin : chargedTwins(gear).entrySet()) {
            if (!aliases.containsKey(twin.getKey().id)) aliases.put(twin.getKey().id, aliases.getOrDefault(twin.getValue().id, twin.getValue().id));
        }
        return aliases;
    }

    // Every dead weapon version -> its live twin of the same name: the
    // "charged" one, else active, normal, fixed or regular, else the first.
    static Map<GearItem, GearItem> chargedTwins(List<GearItem> gear) {
        Map<String, List<GearItem>> weapons = new HashMap<>();
        for (GearItem item : gear) {
            if (item.slot == GearSlot.WEAPON) weapons.computeIfAbsent(item.nameLower, k -> new ArrayList<>()).add(item);
        }
        Map<GearItem, GearItem> twins = new HashMap<>();
        for (List<GearItem> family : weapons.values()) {
            GearItem charged = null;
            for (String want : new String[]{"charged", "active", "normal", "fixed", "regular", ""}) {
                for (GearItem item : family) {
                    if (charged == null && !deadVersion(item) && (want.isEmpty() || item.versionLower.equals(want))) charged = item;
                }
            }
            for (GearItem item : family) {
                if (charged != null && deadVersion(item)) twins.put(item, charged);
            }
        }
        return twins;
    }

    // The charged twin inherits the tradeable dead twin's price: the
    // uncharged Obligator is how you buy the Obligator, so the charged one
    // passes the untradeable gate and the budget modes can afford it.
    static List<GearItem> priceChargedTwins(List<GearItem> gear) {
        Map<Integer, GearItem> priced = new HashMap<>();
        for (var twin : chargedTwins(gear).entrySet()) {
            GearItem dead = twin.getKey();
            GearItem charged = twin.getValue();
            if (dead.tradeable && dead.estimatedPrice != null && (!charged.tradeable || charged.estimatedPrice == null)) priced.putIfAbsent(charged.id, charged.priced(dead.estimatedPrice));
        }
        List<GearItem> out = new ArrayList<>(gear.size());
        for (GearItem item : gear) out.add(priced.getOrDefault(item.id, item));
        return out;
    }

    // A weapon version that cannot attack as it is.
    static boolean deadVersion(GearItem item) {
        String version = item.versionLower;
        return version.contains("uncharged") || version.contains("inactive") || version.contains("broken") || version.contains("locked");
    }

    // One wiki gear row as Gson reads it (gear_prices.json.gz).
    static class GearRow {
        int id, speed;
        String name, version, slot, category, examine;
        boolean isTwoHanded, tradeable, isStandardGear = true, members = true;
        // A price past int range (one 2.45b item) caps instead of wrapping negative.
        Long estimatedPrice;
        Double weight;
        Map<String, Integer> offensive, defensive, bonuses;
    }

    List<GearItem> loadGear() {
        GearRow[] rows = read(GEAR_RESOURCE, GearRow[].class);
        Map<Integer, Map<String, Integer>> sr = loadSkillRequirements();
        List<GearItem> result = new ArrayList<>(rows.length);
        for (GearRow row : rows) {
            GearSlot slot = GearSlot.fromJson(nz(row.slot));
            if (slot == null) continue;
            if (isLeaguesReward(row.name, row.examine)) continue;
            if (isMinigameOnly(row.name)) continue;

            GearItem item = new GearItem(row.id, row.name, row.version, slot, nz(row.category), row.speed, row.isTwoHanded,
                row.isStandardGear || isWronglyFlaggedUsable(row.name), row.tradeable, row.members,
                row.estimatedPrice == null ? null : (int) Math.min(Integer.MAX_VALUE, row.estimatedPrice),
                parseOffensive(row.offensive), parseDefensive(row.defensive), parseBonuses(row.bonuses),
                requirementsFor(row.id, row.name, row.version, sr));
            if (row.weight != null) item.setWeight(row.weight);
            result.add(item);
        }
        result.sort(Comparator.comparing(GearItem::getName).thenComparingInt(GearItem::getId));
        return result;
    }

    static String nz(String s) { return s == null ? "" : s; }

    // Upstream's curated isStandardGear flag marks these permanent main-game
    // upgrades as non-standard (audited 2026-07-05): the Avernic treads
    // upgrade combinations carry real ranged/magic strength, and the
    // Confliction gauntlets are a 7% magic damage glove. Force them usable.
    static boolean isWronglyFlaggedUsable(String name) {
        String n = name == null ? "" : name.toLowerCase();
        return n.startsWith("avernic treads") || n.equals("confliction gauntlets");
    }

    // Leagues-only rewards never enter the corpus - the optimizer suggests
    // main-game gear only. The stat-relevant offenders are the Leagues V
    // "Echo" set (wrongly flagged isStandardGear in the wiki data); the
    // Trailblazer outfits, banners, and trophies are zero-stat cosmetics.
    // The wiki examine text says "league" only on leagues rewards.
    static class Leagues {
        List<String> prefixes = List.of(), contains = List.of(), minigameOnly = List.of();
    }

    static final Leagues LEAGUES = read("leagues_items.json", Leagues.class);

    static boolean isLeaguesReward(String name, String examine) {
        String n = name == null ? "" : name.toLowerCase();
        return LEAGUES.prefixes.stream().anyMatch(n::startsWith) || LEAGUES.contains.stream().anyMatch(n::contains)
            || (examine != null && examine.toLowerCase().contains("league"));
    }

    // Items that only function inside a minigame never enter the corpus.
    // The Barbarian Assault arrows carry ranged strength 125 - stronger
    // than dragon arrows - but can only be fired at penance inside BA
    // (upstream best-dps flagged only two of the four non-standard).
    static boolean isMinigameOnly(String name) {
        return LEAGUES.minigameOnly.contains(name == null ? "" : name.toLowerCase());
    }

    static class ReqRow {
        int id;
        Map<String, Integer> skills = Map.of();
    }

    Map<Integer, Map<String, Integer>> loadSkillRequirements() {
        Map<Integer, Map<String, Integer>> result = new HashMap<>();
        for (ReqRow row : read(REQUIREMENTS_RESOURCE, ReqRow[].class)) {
            Map<String, Integer> levels = new LinkedHashMap<>();
            for (var entry : row.skills.entrySet()) {
                if (entry.getValue() != null) levels.put(entry.getKey(), Math.max(1, entry.getValue()));
            }
            if (!levels.isEmpty()) result.put(row.id, levels);
        }
        return result;
    }

    static GearRequirements requirementsFor(int id, String name, String version, Map<Integer, Map<String, Integer>> sr) {
        Map<String, Integer> skills = sr.getOrDefault(id, Map.of());
        Set<String> quests = questsFor(name, version);
        return skills.isEmpty() && quests.isEmpty() ? GearRequirements.NONE : new GearRequirements(skills, quests);
    }

    // Version-label normalization (field spec 2026-07-18): the noise
    // tokens go ("Awake"; "Post-quest" becomes the bare name - the
    // everyday fight owns it), quest-only rows read "QUEST" loudly
    // (either the literal Quest token, or - for a two-row pair like
    // Vorkath's 'Dragon Slayer II' next to 'Post-quest' - the sibling
    // that is not the post-quest fight). versionTier already sorts
    // anything containing "quest" to the bottom of a bare-name search.
    static List<MonsterStats> normalizeQuestVersions(List<MonsterStats> monsters) {
        Map<String, List<MonsterStats>> bn = new LinkedHashMap<>();
        for (MonsterStats monster : monsters) {
            bn.computeIfAbsent(monster.nameLower, k -> new ArrayList<>()).add(monster);
        }
        List<MonsterStats> out = new ArrayList<>(monsters.size());
        for (List<MonsterStats> group : bn.values()) {
            boolean pairWithPostQuest = group.size() == 2 && group.stream()
                .anyMatch(m -> Names.lower(m.version).contains("post-quest"));
            for (MonsterStats monster : group) {
                String version = monster.version;
                if (version == null || version.isEmpty()) {
                    out.add(monster);
                    continue;
                }
                List<String> kept = new ArrayList<>();
                boolean quest = false;
                for (String token : version.split(",\\s*")) {
                    if (token.equalsIgnoreCase("awake") || token.equalsIgnoreCase("post-quest")) continue;
                    if (token.equalsIgnoreCase("quest")) {
                        quest = true;
                        continue;
                    }
                    kept.add(token);
                }
                if (pairWithPostQuest && !quest && !Names.lower(version).contains("post-quest")) {
                    // The non-post-quest half of the pair IS the quest fight.
                    quest = true;
                    kept.clear();
                }
                String normalized = String.join(", ", kept);
                if (quest) normalized = normalized.isEmpty() ? "QUEST" : normalized + ", QUEST";
                out.add(normalized.equals(version) ? monster : monster.withVersion(normalized));
            }
        }
        return out;
    }

    // One wiki monster row as Gson reads it (monsters.json.gz); the stat
    // blocks stay maps so a group key can print them whole.
    static class MonsterRow {
        int id = -1, level, speed = 4, size = 1;
        String name, version, max_hit;
        List<String> style = List.of(), attributes = List.of();
        Map<String, Integer> skills, offensive, defensive;
        Map<String, String> immunities;
        Map<String, Object> weakness;
        boolean is_slayer_monster;

        // Leagues echo bosses are seasonal, never main-game (Andrew 2026-09-03:
        // "should not be able to search 'echo' version in main mode").
        // Nightmare Zone versions too (Andrew 2026-09-04: "nobody needs theory
        // crafting for that") - they swamped a search for the Nightmare.
        boolean echo() { return nz(name).contains("(Echo)") || nz(name).contains("(Nightmare Zone)"); }

        // Everything the engine reads from a monster - rows agreeing on this
        // are one entry. The Wardens' Core-ejected rows are stat-identical to
        // their Active siblings, but the engine reads that version as a
        // MECHANIC (the core's always-max rule) - collapsing them would erase
        // the spec-dump phase from the corpus entirely.
        String statKey() {
            String mechanicVersion = "Core-ejected".equals(version) ? "Core-ejected" : "";
            return v(skills, "def", 1) + "|" + v(skills, "magic", 1) + "|" + v(offensive, "magic", 0) + "|" + defensive + "|" + attributes
                + "|" + is_slayer_monster + "|" + weakness + "|" + size + "|" + mechanicVersion;
        }
    }

    List<MonsterStats> loadMonsters() {
        MonsterRow[] rows = read(MONSTER_RESOURCE, MonsterRow[].class);
        // The wiki data lists one row per SPAWN - Tormented Demon (1)..(4)
        // are four combat-identical rows. Collapse same-name rows whose
        // combat-relevant stats match, and drop the version label entirely
        // when a name has only one distinct stat block (Dusk keeps its
        // First/Second form; the four TDs become one unlabeled entry).
        Map<String, Set<String>> skbn = new HashMap<>();
        // Collapsed groups display the HIGHEST combat level among their spawns.
        Map<String, Integer> mlbg = new HashMap<>();
        for (MonsterRow row : rows) {
            if (row.echo()) continue;
            String nk = Names.lower(row.name);
            String sk = row.statKey();
            skbn.computeIfAbsent(nk, k -> new LinkedHashSet<>()).add(sk);
            mlbg.merge(nk + "|" + sk, row.level, Math::max);
        }

        Set<String> emitted = new HashSet<>();
        List<MonsterStats> result = new ArrayList<>(rows.length);
        for (MonsterRow row : rows) {
            if (row.echo()) continue;
            String nk = Names.lower(row.name);
            String groupKey = nk + "|" + row.statKey();
            // Emit the HIGHEST-LEVEL spawn of each collapsed group, so the
            // offensive sheet (used for incoming dps) matches the combat
            // level the label displays.
            if (row.level != mlbg.get(groupKey) || !emitted.add(groupKey)) continue;
            boolean distinctVersions = skbn.get(nk).size() > 1;
            List<String> attributes = new ArrayList<>();
            if (row.attributes != null) for (String attr : row.attributes) {
                if (attr != null) attributes.add(attr);
            }
            // Burn immunity rides the attribute list as a synthetic marker
            // (no MonsterStats signature churn): the eclipse/scorching burn
            // class is a NORMAL burn, blocked by Normal or Strong immunity
            // (official calc isImmuneToNormalBurns; Weak does not block it).
            String burn = row.immunities == null ? "" : nz(row.immunities.get("burn"));
            if ("normal".equalsIgnoreCase(burn) || "strong".equalsIgnoreCase(burn)) attributes.add("burn_immune");

            // The Maggot King fights at range until ~65% hp - melee CANNOT
            // land on the Far phase (wiki: "cannot be attacked with melee
            // until it falls below ~980 hitpoints"; field report 2026-08-20:
            // Far recommended a melee set). The corpus carries no attribute
            // for it, so the marker rides here like burn_immune.
            if ("Maggot King".equals(row.name) && "Far".equalsIgnoreCase(row.version)) attributes.add("immune_melee");

            // The ejected core is a 1x1 target - the wiki row carries the
            // Warden's 5x5 frame, which handed the crystal halberd's sweep a
            // phantom second hit and outranked the DDS dump (field report
            // 2026-08-06). Size is the one stat the always-max rule still
            // reads (halberd sweep, scythe cleave).
            int size = "Core-ejected".equals(row.version) ? 1 : row.size;
            result.add(new MonsterStats(row.id, nz(row.name), distinctVersions ? nz(row.version) : "", mlbg.get(groupKey), v(row.skills, "hp", 1),
                size, v(row.skills, "def", 1), v(row.skills, "magic", 1), v(row.offensive, "magic", 0),
                parseMonsterDefences(row.defensive), new MonsterOffence(v(row.skills, "atk", 1),
                    v(row.skills, "str", 1), v(row.skills, "ranged", 1), v(row.skills, "magic", 1),
                    v(row.offensive, "atk", 0), v(row.offensive, "str", 0), v(row.offensive, "ranged", 0),
                    v(row.offensive, "ranged_str", 0), v(row.offensive, "magic", 0),
                    v(row.offensive, "magic_str", 0), row.speed, styleList(row.style),
                    MaxHits.parse(nz(row.max_hit))), attributes,
                row.is_slayer_monster || knownSlayerMonster(row.name),
                row.weakness == null ? "" : nz((String) row.weakness.get("element")), v(row.weakness, "severity", 0)));
        }
        result.sort(Comparator.comparing(MonsterStats::getName).thenComparing(MonsterStats::getVersion).thenComparingInt(MonsterStats::getId));
        return result;
    }

    static List<String> styleList(List<String> raw) {
        List<String> styles = new ArrayList<>();
        if (raw != null) for (String e : raw) {
            if (e == null) continue;
            // "Ranged <br/> Typeless" is two styles; stray DEL characters
            // (Araxxor, Dusk) are wiki noise.
            for (String style : e.replace('\u007f', ' ').split("(?i)<br\\s*/?>")) {
                if (!style.trim().isEmpty()) styles.add(style.trim());
            }
        }
        return styles;
    }

    static class SpellRow {
        String name, spellbook, element;
        int max_hit;
        boolean unselectable;
    }

    List<SpellStats> loadSpells() {
        List<SpellStats> result = new ArrayList<>();
        for (SpellRow row : read(SPELL_RESOURCE, SpellRow[].class)) {
            String name = nz(row.name);
            if (row.max_hit <= 0 && !"Magic Dart".equals(name)) continue;
            // Effect-only spells (leagues echoes, boss mechanics - e.g.
            // Flames of Cerberus) are flagged unselectable in the wiki data;
            // a player can never cast them, so they never enter the corpus.
            if (row.unselectable) continue;
            result.add(new SpellStats(name, "Magic Dart".equals(name) ? 1 : row.max_hit, spellLevel(name), nz(row.spellbook), nz(row.element)));
        }
        result.sort(Comparator.comparingInt(SpellStats::getMaxHit).thenComparing(SpellStats::getName));
        return result;
    }

    // Casting level for a spell name; unknown names fall back to 1.
    static int spellLevel(String name) { return RULES.spellLevels.getOrDefault(name == null ? "" : name, 1); }

    static StatBlock parseOffensive(Map<String, Integer> m) {
        if (m == null) return StatBlock.ZERO;
        int[] c = combat(m);
        return new StatBlock(c[0], c[1], c[2], c[3], c[4], 0, 0, 0, 0);
    }

    static StatBlock parseDefensive(Map<String, Integer> m) {
        if (m == null) return StatBlock.ZERO;
        int[] c = combat(m);
        return new StatBlock(c[0], c[1], c[2], c[3], c[4], 0, v(m, "light", 0), v(m, "standard", 0), v(m, "heavy", 0));
    }

    static MonsterDefences parseMonsterDefences(Map<String, Integer> m) {
        if (m == null) return MonsterDefences.ZERO;
        int[] c = combat(m);
        return new MonsterDefences(c[0], c[1], c[2], c[3], c[4], v(m, "flat_armour", 0), v(m, "light", 0), v(m, "standard", 0), v(m, "heavy", 0));
    }

    static StatBlock parseBonuses(Map<String, Integer> m) {
        if (m == null) return StatBlock.ZERO;
        return new StatBlock(0, 0, 0, 0, 0, v(m, "str", 0), v(m, "ranged_str", 0), v(m, "magic_str", 0), v(m, "prayer", 0));
    }

    // stab, slash, crush, magic, ranged - the five every stat block shares.
    static int[] combat(Map<String, Integer> m) {
        return new int[]{v(m, "stab", 0), v(m, "slash", 0), v(m, "crush", 0), v(m, "magic", 0), v(m, "ranged", 0)};
    }

    // A stat block's number, the fallback where the block or the key is missing (or null).
    static int v(Map<String, ?> m, String key, int fallback) {
        Object x = m == null ? null : m.get(key);
        return x instanceof Number ? ((Number) x).intValue() : fallback;
    }

    static boolean knownSlayerMonster(String name) {
        String normalized = name == null ? "" : Names.lower(name);
        return RULES.slayerContains.stream().anyMatch(normalized::contains) || RULES.slayerStartsWith.stream().anyMatch(normalized::startsWith);
    }

    // Quest unlocks implied by an item's name and version, in resource rule
    // order. LinkedHashSet, so a quest named by two rules keeps the position of
    // its first match - the same behaviour the old requireIf chain had.
    static Set<String> questsFor(String name, String version) {
        String item = ((name == null ? "" : name) + " " + (version == null ? "" : version)) .toLowerCase(Locale.ROOT);
        Set<String> quests = new LinkedHashSet<>();
        for (QuestRule rule : RULES.questRules) {
            for (String term : rule.terms) {
                if (item.contains(term)) {
                    quests.add(rule.quest);
                    break;
                }
            }
        }
        return quests;
    }
}
